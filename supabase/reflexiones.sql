create table if not exists public.reflexiones (
  id bigint generated by default as identity primary key,
  titulo text not null,
  descripcion text,
  versiculo text,
  fecha date not null,
  imagen_url text not null,
  me_gusta integer not null default 0,
  activa boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.reflexiones enable row level security;

create policy "Public puede leer reflexiones activas"
  on public.reflexiones for select
  using (activa = true);

create policy "Usuarios autenticados administran reflexiones"
  on public.reflexiones for all
  to authenticated
  using (true)
  with check (true);

insert into storage.buckets (id, name, public)
values ('reflexiones', 'reflexiones', true)
on conflict (id) do update set public = true;

create policy "Public puede ver imagenes de reflexiones"
  on storage.objects for select
  using (bucket_id = 'reflexiones');

create policy "Usuarios autenticados suben imagenes de reflexiones"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'reflexiones');

create policy "Usuarios autenticados eliminan imagenes de reflexiones"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'reflexiones');

create or replace function public.incrementar_me_gusta_reflexion(reflexion_id bigint)
returns void
language sql
security definer
set search_path = public
as $$
  update public.reflexiones
  set me_gusta = coalesce(me_gusta, 0) + 1
  where id = reflexion_id and activa = true;
$$;

revoke all on function public.incrementar_me_gusta_reflexion(bigint) from public;
grant execute on function public.incrementar_me_gusta_reflexion(bigint) to anon, authenticated;
